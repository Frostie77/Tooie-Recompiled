#!/usr/bin/env python3
"""Generate the checked-in helper SPIR-V; no shader compiler needed at runtime.
Use the Android NDK r27d shader-tools glslc and spirv-val (or compatible tools).
The fragment output Location operand is patched before module creation to select
an attachment. Validate every supported location here, not just location zero.
"""
import argparse
import pathlib
import struct
import subprocess
import tempfile
parser = argparse.ArgumentParser()
parser.add_argument('--glslc', default='glslc')
parser.add_argument('--spirv-val', default='spirv-val')
args = parser.parse_args()
root = pathlib.Path(__file__).resolve().parents[1]
plume = root / 'lib/rt64/src/contrib/plume'
lines = ['// Generated by tools/generate_vulkan_clear_shaders.py. Do not edit.',
         '// GLSL sources: shaders/color_clear.vert and shaders/color_clear.frag.',
         '#pragma once', '#include <cstdint>', 'namespace plume {']
with tempfile.TemporaryDirectory() as directory:
    for stage in ('vert', 'frag'):
        binary = pathlib.Path(directory) / f'clear.{stage}.spv'
        subprocess.run([args.glslc, '--target-env=vulkan1.2', '-O',
                        str(plume / f'shaders/color_clear.{stage}'), '-o', str(binary)], check=True)
        subprocess.run([args.spirv_val, '--target-env', 'vulkan1.2', str(binary)], check=True)
        words = list(struct.unpack(f'<{binary.stat().st_size // 4}I', binary.read_bytes()))
        if stage == 'frag':
            locations = []
            offset = 5
            while offset < len(words):
                count, op = words[offset] >> 16, words[offset] & 0xffff
                # OpDecorate <output id> Location 0
                if op == 71 and count == 4 and words[offset + 2] == 30:
                    locations.append(offset + 3)
                offset += count
            assert len(locations) == 1 and words[locations[0]] == 0
            location = locations[0]
            for index in range(8):
                patched = words.copy()
                patched[location] = index
                binary.write_bytes(struct.pack(f'<{len(patched)}I', *patched))
                subprocess.run([args.spirv_val, '--target-env', 'vulkan1.2', str(binary)], check=True)
            lines += [f'constexpr uint32_t ColorClearFragmentLocationWord = {location};',
                      'constexpr uint32_t ColorClearMaxAttachments = 8;']
        name = 'ColorClearVertex' if stage == 'vert' else 'ColorClearFragment'
        lines += [f'constexpr uint32_t {name}[] = {{']
        for offset in range(0, len(words), 8):
            lines += ['    ' + ', '.join(f'0x{word:08x}' for word in words[offset:offset + 8]) + ',']
        lines += ['};']
lines += ['} // namespace plume', '']
(plume / 'plume_vulkan_clear_shaders.h').write_text('\n'.join(lines))
# The readback test's ordinary draw deliberately has no clear rectangle logic.
with tempfile.TemporaryDirectory() as directory:
    binary = pathlib.Path(directory) / 'draw.spv'
    subprocess.run([args.glslc, '--target-env=vulkan1.2', '-O',
                    str(root / 'tests/shaders/vulkan_draw.frag'), '-o', str(binary)], check=True)
    subprocess.run([args.spirv_val, '--target-env', 'vulkan1.2', str(binary)], check=True)
    words = struct.unpack(f'<{binary.stat().st_size // 4}I', binary.read_bytes())
    lines = ['// Generated by tools/generate_vulkan_clear_shaders.py from shaders/vulkan_draw.frag.',
             '#pragma once', '#include <cstdint>', 'constexpr uint32_t OrdinaryDrawFragment[] = {']
    for offset in range(0, len(words), 8):
        lines += ['    ' + ', '.join(f'0x{word:08x}' for word in words[offset:offset + 8]) + ',']
    lines += ['};', '']
    (root / 'tests/android_vulkan_draw_test_shaders.h').write_text('\n'.join(lines))
